export function getModuleBySlug(slug: string | undefined): LearningModule | undefined {
  if (!slug) return undefined;
  return MODULES.find((m) => m.slug === slug || m.id === slug);
}

export function getHeroModules(): LearningModule[] {
  return MODULES.filter((m) => m.featuredInHero);
}

export function getTop10Modules(): LearningModule[] {
  return [...MODULES]
    .filter((m) => m.topRank != null)
    .sort((a, b) => (a.topRank || 99) - (b.topRank || 99))
    .slice(0, 10);
}
